// popup.js - Copy all issues functionality

// Simulated issues data - in a real extension this would come from the scan results
// Format: each issue has name, explanation, selector, guidance, and page context
const ISSUE_TEMPLATE = (issue, index) => `
### Issue ${index + 1}: ${issue.name}

**Explanation:** ${issue.explanation}

**Affected Element:** ${issue.selector || 'Not specified'}

**Guidance:** ${issue.guidance || 'Review and fix the issue'}

---`;

const CopyAllIssues = {
  // Format issues as Markdown text
  formatAsMarkdown(issues) {
    const pageUrl = issues.length > 0 ? issues[0].pageUrl : 'Current page';
    const total = issues.length;
    
    let text = `# cobalt-hub Issues Report\n\n`;
    text += `- **Page URL:** ${pageUrl}\n`;
    text += `- **Total Findings:** ${total}\n\n`;
    
    text += '## Findings\n\n';
    
    issues.forEach((issue, index) => {
      text += ISSUE_TEMPLATE(issue, index);
    });
    
    text += '\n---\n*Report generated by cobalt-hub browser extension*';
    
    return text;
  },
  
  // Format issues as plain text
  formatAsPlainText(issues) {
    const pageUrl = issues.length > 0 ? issues[0].pageUrl : 'Current page';
    const total = issues.length;
    
    let text = `cobalt-hub Issues Report\n`;
    text += `=====================\n\n`;
    text += `Page URL: ${pageUrl}\n`;
    text += `Total Findings: ${total}\n\n`;
    
    issues.forEach((issue, index) => {
      text += `Issue ${index + 1}: ${issue.name}\n`;
      text += `Explanation: ${issue.explanation}\n`;
      text += `Affected Element: ${issue.selector || 'Not specified'}\n`;
      text += `Guidance: ${issue.guidance || 'Review and fix the issue'}\n`;
      text += '---\n\n';
    });
    
    text += 'Report generated by cobalt-hub browser extension';
    
    return text;
  },
  
  // Show status message
  showStatus(message, isError = false) {
    const statusEl = document.getElementById('status');
    const statusText = document.getElementById('status-text');
    const copyBtn = document.getElementById('copy-btn');
    
    statusText.textContent = message;
    statusEl.style.display = 'block';
    statusEl.classList.toggle('error', isError);
    
    // Auto-hide after 5 seconds
    setTimeout(() => {
      statusEl.style.display = 'none';
    }, 5000);
  },
  
  // Copy text to clipboard
  async copyToClipboard(text) {
    try {
      await navigator.clipboard.writeText(text);
      this.showStatus('Issues copied to clipboard!', false);
      return true;
    } catch (err) {
      // Fallback for older browsers
      const textarea = document.createElement('textarea');
      textarea.value = text;
      textarea.style.position = 'fixed';
      textarea.style.opacity = '0';
      document.body.appendChild(textarea);
      textarea.select();
      try {
        document.execCommand('copy');
        this.showStatus('Issues copied to clipboard!', false);
      } catch (e) {
        this.showStatus('Failed to copy issues', true);
      }
      document.body.removeChild(textarea);
      return false;
    }
  },
  
  // Initialize the popup
  init() {
    const copyBtn = document.getElementById('copy-btn');
    const issuesText = document.getElementById('issues-text');
    const statusEl = document.getElementById('status');
    
    // Populate with sample issues (in production, these would come from scan results)
    const sampleIssues = [
      {
        name: 'Unused CSS',
        explanation: 'CSS rules that are not used by any element on the page',
        selector: '.unused-class',
        guidance: 'Remove unused CSS to reduce file size and improve load times',
        pageUrl: window.location.href
      },
      {
        name: 'Large Image',
        explanation: 'Image dimensions exceed reasonable size for the layout',
        selector: '.hero-image',
        guidance: 'Optimize or compress the image, or use responsive dimensions',
        pageUrl: window.location.href
      },
      {
        name: 'Missing Alt Text',
        explanation: 'Image missing descriptive alt attribute for accessibility',
        selector: '.logo-img',
        guidance: 'Add meaningful alt text describing the image content',
        pageUrl: window.location.href
      }
    ];
    
    // Format and display issues
    const markdownText = this.formatAsMarkdown(sampleIssues);
    const plainText = this.formatAsPlainText(sampleIssues);
    
    // Set the textarea content (Markdown format)
    issuesText.value = markdownText;
    
    // Copy button handler
    copyBtn.addEventListener('click', async () => {
      const success = await this.copyToClipboard(markdownText);
      if (!success) {
        // Try plain text fallback
        this.copyToClipboard(plainText);
      }
    });
    
    // Close on esc key
    document.addEventListener('keydown', (e) => {
      if (e.key === 'Escape') {
        window.close();
      }
    });
  }
};

// Initialize when DOM is ready
if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', () => CopyAllIssues.init());
} else {
  CopyAllIssues.init();
}
